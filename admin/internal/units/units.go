// Package units renders systemd units from the config and drives systemctl.
// Units are written to /run/systemd/system so they vanish on reboot and are
// regenerated from the YAML, which stays the single source of truth.
package units

import (
	"context"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/jwoglom/osaid-simulator-pi/admin/internal/config"
	"github.com/jwoglom/osaid-simulator-pi/admin/internal/system"
)

const Prefix = "osaid-sim-"

type Paths struct {
	UnitDir  string // /run/systemd/system
	StateDir string // /var/lib/osaid
}

func UnitName(sim string) string { return Prefix + sim + ".service" }

func (p Paths) SimDir(sim string) string  { return filepath.Join(p.StateDir, "sims", sim) }
func (p Paths) DataDir(sim string) string { return filepath.Join(p.SimDir(sim), "data") }
func (p Paths) Current(sim string) string { return filepath.Join(p.SimDir(sim), "current") }

// Render produces the unit text for one simulator.
func Render(cfg *config.Config, s config.Simulator, p Paths) string {
	s = cfg.Effective(s)
	var b strings.Builder
	conflicts := []string{"bluetooth.service"}
	for _, peer := range cfg.Peers(s) {
		conflicts = append(conflicts, UnitName(peer))
	}
	fmt.Fprintf(&b, "# Generated by osaid-admin from osaid.yaml. Do not edit; edit the YAML.\n")
	fmt.Fprintf(&b, "[Unit]\nDescription=OSAID simulator: %s\n", s.Title)
	fmt.Fprintf(&b, "Conflicts=%s\n", strings.Join(conflicts, " "))
	fmt.Fprintf(&b, "After=hciuart.service osaid-admin.service\n")
	fmt.Fprintf(&b, "StartLimitIntervalSec=60\nStartLimitBurst=10\n\n")
	fmt.Fprintf(&b, "[Service]\n")
	// The base OS can restore a soft rfkill block even while bluetoothd is
	// masked. Unblock the radio before each start; '+' runs this preparation
	// as root while the simulator itself still runs as its configured user.
	fmt.Fprintf(&b, "ExecStartPre=+/usr/sbin/rfkill unblock bluetooth\n")
	if s.User != "root" {
		fmt.Fprintf(&b, "User=%s\n", s.User)
	}
	fmt.Fprintf(&b, "WorkingDirectory=%s\n", p.DataDir(s.Name))
	fmt.Fprintf(&b, "EnvironmentFile=-%s\n", filepath.Join(p.SimDir(s.Name), "flags.env"))
	fmt.Fprintf(&b, "Environment=OSAID_BUILD=%s OSAID_DATA=%s OSAID_NAME=%s\n", p.Current(s.Name), p.DataDir(s.Name), s.Name)
	keys := make([]string, 0, len(s.Env))
	for k := range s.Env {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		fmt.Fprintf(&b, "Environment=%q\n", k+"="+s.Env[k])
	}
	fmt.Fprintf(&b, "ExecStart=%s\n", filepath.Join(p.SimDir(s.Name), "run.sh"))
	if len(s.Capabilities) > 0 {
		fmt.Fprintf(&b, "AmbientCapabilities=%s\n", strings.Join(s.Capabilities, " "))
	}
	fmt.Fprintf(&b, "Restart=%s\nRestartSec=2\n", s.Restart)
	fmt.Fprintf(&b, "KillMode=control-group\nTimeoutStopSec=5\n")
	if s.MemoryMax != "" {
		fmt.Fprintf(&b, "MemoryMax=%s\nOOMPolicy=kill\n", s.MemoryMax)
	}
	fmt.Fprintf(&b, "OOMScoreAdjust=500\n")
	fmt.Fprintf(&b, "StandardOutput=journal\nStandardError=journal\nSyslogIdentifier=%s\n", s.Name)
	return b.String()
}

// RunScript is the per-simulator launcher. It keeps the exec line out of unit
// quoting rules and prefixes PATH with the active build.
func RunScript(s config.Simulator) string {
	return "#!/bin/sh\n# Generated by osaid-admin. Edit the exec line in osaid.yaml instead.\n" +
		"export PATH=\"$OSAID_BUILD:$PATH\"\ncd \"$OSAID_DATA\" || exit 1\n" +
		"exec " + s.Exec + "\n"
}

// FlagsEnv renders the EnvironmentFile holding the editable FLAGS value.
func FlagsEnv(flags string) string {
	flags = strings.TrimSpace(flags)
	return "FLAGS=" + flags + "\n"
}

type Manager struct {
	Run   system.Runner
	Paths Paths
}

// Sync writes units, run scripts and flags for every simulator, removes units for
// simulators no longer configured, reloads systemd and makes sure user/dirs exist.
func (m *Manager) Sync(ctx context.Context, cfg *config.Config) error {
	if err := os.MkdirAll(m.Paths.UnitDir, 0o755); err != nil {
		return err
	}
	want := map[string]bool{}
	for _, raw := range cfg.Simulators {
		s := cfg.Effective(raw)
		want[UnitName(s.Name)] = true
		if err := m.writeSimFiles(cfg, s); err != nil {
			return fmt.Errorf("%s: %w", s.Name, err)
		}
	}
	entries, _ := filepath.Glob(filepath.Join(m.Paths.UnitDir, Prefix+"*.service"))
	for _, e := range entries {
		if !want[filepath.Base(e)] {
			_, _ = m.Run.Run(ctx, "systemctl", "stop", filepath.Base(e))
			_ = os.Remove(e)
		}
	}
	_, err := m.Run.Run(ctx, "systemctl", "daemon-reload")
	return err
}

func (m *Manager) writeSimFiles(cfg *config.Config, s config.Simulator) error {
	dir := m.Paths.SimDir(s.Name)
	for _, d := range []string{dir, m.Paths.DataDir(s.Name), filepath.Join(dir, "builds"), filepath.Join(dir, "uploads")} {
		if err := os.MkdirAll(d, 0o755); err != nil {
			return err
		}
	}
	if s.User != "root" && !m.Run.Mock() {
		_, _ = m.Run.Run(context.Background(), "chown", "-R", s.User, m.Paths.DataDir(s.Name))
	}
	if err := writeIfChanged(filepath.Join(dir, "run.sh"), RunScript(s), 0o755); err != nil {
		return err
	}
	// flags.env is only seeded here; SetFlags owns later edits so the YAML's flags
	// are the default and the UI's value wins once set.
	if _, err := os.Stat(filepath.Join(dir, "flags.env")); os.IsNotExist(err) {
		if err := writeIfChanged(filepath.Join(dir, "flags.env"), FlagsEnv(s.Flags), 0o644); err != nil {
			return err
		}
	}
	return writeIfChanged(filepath.Join(m.Paths.UnitDir, UnitName(s.Name)), Render(cfg, s, m.Paths), 0o644)
}

func writeIfChanged(path, content string, mode os.FileMode) error {
	if old, err := os.ReadFile(path); err == nil && string(old) == content {
		return os.Chmod(path, mode)
	}
	return os.WriteFile(path, []byte(content), mode)
}

// Flags reads the live FLAGS value for a simulator.
func (m *Manager) Flags(sim string) string {
	b, err := os.ReadFile(filepath.Join(m.Paths.SimDir(sim), "flags.env"))
	if err != nil {
		return ""
	}
	for _, line := range strings.Split(string(b), "\n") {
		if strings.HasPrefix(line, "FLAGS=") {
			return strings.TrimPrefix(line, "FLAGS=")
		}
	}
	return ""
}

func (m *Manager) SetFlags(sim, flags string) error {
	if strings.ContainsAny(flags, "\n\r") {
		return fmt.Errorf("flags must be a single line")
	}
	return os.WriteFile(filepath.Join(m.Paths.SimDir(sim), "flags.env"), []byte(FlagsEnv(flags)), 0o644)
}

type Status struct {
	Active   string `json:"active"` // ActiveState
	Sub      string `json:"sub"`    // SubState
	PID      int    `json:"pid"`
	MemoryKB int64  `json:"memory_kb"`
}

func (m *Manager) Status(ctx context.Context, sim string) Status {
	out, _ := m.Run.Run(ctx, "systemctl", "show", "-p", "ActiveState", "-p", "SubState", "-p", "MainPID", "-p", "MemoryCurrent", UnitName(sim))
	st := Status{Active: "unknown"}
	for _, line := range strings.Split(out, "\n") {
		k, v, ok := strings.Cut(line, "=")
		if !ok {
			continue
		}
		switch k {
		case "ActiveState":
			st.Active = v
		case "SubState":
			st.Sub = v
		case "MainPID":
			fmt.Sscan(v, &st.PID)
		case "MemoryCurrent":
			var n int64
			if _, err := fmt.Sscan(v, &n); err == nil {
				st.MemoryKB = n / 1024
			}
		}
	}
	return st
}

func (m *Manager) Start(ctx context.Context, sim string) error {
	_, err := m.Run.Run(ctx, "systemctl", "start", "--no-block", UnitName(sim))
	return err
}
func (m *Manager) Stop(ctx context.Context, sim string) error {
	_, err := m.Run.Run(ctx, "systemctl", "stop", UnitName(sim))
	return err
}
func (m *Manager) Restart(ctx context.Context, sim string) error {
	_, err := m.Run.Run(ctx, "systemctl", "restart", "--no-block", UnitName(sim))
	return err
}

// Kill sends SIGKILL to every process in the unit's cgroup and leaves it
// stopped (Restart= would otherwise bring it straight back).
func (m *Manager) Kill(ctx context.Context, sim string) error {
	if _, err := m.Run.Run(ctx, "systemctl", "kill", "--signal=SIGKILL", UnitName(sim)); err != nil {
		return err
	}
	_, err := m.Run.Run(ctx, "systemctl", "stop", UnitName(sim))
	return err
}
